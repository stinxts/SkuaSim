using System.Globalization;
using System.Text;
using SkuaSim.Core.Scenarios;

namespace SkuaSim.Core.Runtime;

/// <summary>
/// Fills the bug report template (<c>docs/BUG_REPORT_TEMPLATE.md</c>) from a diagnostic scenario (made in Skua by
/// <c>tools/skua/SkuaSim_Diagnostic.cs</c>) and the SkuaSim run of it: the character, the reproduction result, the data
/// gaps that make the result less certain, and a starting point for the regression asserts. The sections only the
/// reporter can write (what went wrong, the real log) are left as prompts.
/// </summary>
public static class BugReportWriter
{
    public const string FillMarker = "✏️";

    public static string ToMarkdown(Scenario diagnostic, SimulationReport report, string? diagnosticPath = null)
    {
        var sb = new StringBuilder();
        var script = string.IsNullOrWhiteSpace(diagnostic.Script) ? Path.GetFileName(report.ScriptPath) : diagnostic.Script;
        sb.AppendLine($"# Bug report — `{script}`");
        sb.AppendLine();
        sb.AppendLine($"> Sections marked {FillMarker} are for the reporter. Everything else was generated by SkuaSim from the diagnostic file" +
                      (diagnosticPath == null ? "." : $" `{Path.GetFileName(diagnosticPath)}`."));
        sb.AppendLine("> The diagnostic file lists the character's items, quest progress and options, never the character name.");
        sb.AppendLine();

        sb.AppendLine($"## What went wrong {FillMarker}");
        sb.AppendLine("- **What the script did:** ");
        sb.AppendLine("- **What it should have done:** ");
        sb.AppendLine("- **Where / when it happens** (map, step, after how long, every time or sometimes): ");
        sb.AppendLine();

        sb.AppendLine($"## Real run {FillMarker}");
        sb.AppendLine("- **Script version** (Skua's script list date or the Scripts repository commit): ");
        sb.AppendLine("- **Other scripts or plugins running at the same time:** ");
        sb.AppendLine("- **Skua log** (the last lines before the problem):");
        sb.AppendLine("```text");
        sb.AppendLine();
        sb.AppendLine("```");
        sb.AppendLine();

        AppendCharacter(sb, diagnostic);
        AppendReproduction(sb, diagnostic, report, diagnosticPath);
        AppendDataGaps(sb, report);
        AppendRegressionTest(sb, diagnostic, report, diagnosticPath);
        return sb.ToString();
    }

    private static void AppendCharacter(StringBuilder sb, Scenario d)
    {
        var p = d.Player;
        sb.AppendLine("## Character (from the diagnostic)");
        if (!string.IsNullOrWhiteSpace(d.Description))
            sb.AppendLine($"> {d.Description}");
        sb.AppendLine();
        sb.AppendLine("| | |");
        sb.AppendLine("|---|---|");
        sb.AppendLine($"| Level / class | {p.Level} / {p.Class ?? "-"} (rank {p.ClassRank}) |");
        sb.AppendLine($"| Member | {(p.IsMember ? "yes" : "no")} |");
        sb.AppendLine($"| Gold / ACs | {p.Gold.ToString("N0", CultureInfo.InvariantCulture)} / {p.Coins.ToString("N0", CultureInfo.InvariantCulture)} |");
        sb.AppendLine($"| Location | `{d.Location.Map}` (`{d.Location.Cell}` / `{d.Location.Pad}`) |");
        sb.AppendLine($"| Captured at | {(d.StartDate != null ? d.EffectiveStartUtc.ToString("yyyy-MM-dd HH:mm 'UTC'", CultureInfo.InvariantCulture) : "-")} |");
        sb.AppendLine($"| Items (inventory / bank / house / temp) | {d.Inventory.Count} / {d.Bank.Count} / {d.House.Count} / {d.TempInventory.Count} |");
        var equipped = d.Inventory.Where(i => i.Equipped && !string.IsNullOrWhiteSpace(i.Name)).Select(i => i.Name!).ToList();
        if (equipped.Count > 0)
            sb.AppendLine($"| Equipped | {Cell(string.Join(", ", equipped))} |");
        sb.AppendLine($"| Quests (active / story slots / dailies done) | {d.Quests.Active.Count} / {d.Quests.SlotProgress.Count} / {d.Quests.DailiesCompleted.Count} |");
        sb.AppendLine($"| Factions | {d.Factions.Count} |");
        var boosts = new[] { (d.Boosts.XpBoost, "XP"), (d.Boosts.ClassPointsBoost, "Class"), (d.Boosts.GoldBoost, "Gold"), (d.Boosts.RepBoost, "Rep") }
            .Where(b => b.Item1).Select(b => b.Item2).ToList();
        sb.AppendLine($"| Boosts running | {(boosts.Count > 0 ? string.Join(", ", boosts) : "none")} |");
        var unlocks = d.Enhancements.UnlockedAwe.Concat(d.Enhancements.UnlockedForge).ToList();
        sb.AppendLine($"| Awe / Forge unlocks | {(unlocks.Count > 0 ? Cell(string.Join(", ", unlocks)) : "none")} |");
        sb.AppendLine($"| Script options | {(d.Options.Count > 0 ? Cell(string.Join(", ", d.Options.Select(kv => $"{kv.Key}={kv.Value}"))) : "none (defaults)")} |");
        var changedOptions = d.BotOptions.Where(kv => !Api.OptionsApi.IsDefaultValue(kv.Key, kv.Value)).ToList();
        if (d.BotOptions.Count > 0)
            sb.AppendLine($"| Client options changed from Skua's defaults | {(changedOptions.Count > 0 ? Cell(string.Join(", ", changedOptions.Select(kv => $"{kv.Key}={kv.Value}"))) : "none")} |");
        sb.AppendLine();
    }

    private static void AppendReproduction(StringBuilder sb, Scenario d, SimulationReport r, string? diagnosticPath)
    {
        sb.AppendLine("## SkuaSim reproduction");
        sb.AppendLine($"- **Command:** `skuasim run --scenario \"{diagnosticPath ?? "<diagnostic.json>"}\"" +
                      (string.IsNullOrWhiteSpace(d.Script) ? $" \"{r.ScriptPath}\"" : "") + $" --seed {r.Seed}`");
        sb.AppendLine($"- **Script:** `{r.ScriptPath}`");
        sb.AppendLine($"- **Outcome:** **{r.Outcome}**{(string.IsNullOrEmpty(r.StopReason) ? "" : $" ({r.StopReason})")}");
        sb.AppendLine($"- **Virtual time:** `{FormatVirtual(r.VirtualDuration)}` · seed `{r.Seed}`" +
                      (string.IsNullOrEmpty(r.DataInfo) ? "" : $" · data `{r.DataInfo}`"));
        sb.AppendLine($"- **Activity:** {r.Kills:N0} kills, {r.Deaths:N0} deaths, {r.QuestsCompleted:N0} quest turn-ins, {r.DropsPicked:N0} drops, " +
                      $"maps {(r.MapsVisited.Count > 0 ? string.Join(", ", r.MapsVisited.Select(m => $"`{m}`")) : "none")}");
        sb.AppendLine($"- **End state:** level {r.FinalState.Level}, {r.FinalState.Gold:N0} gold, in `{r.FinalState.Map}` (`{r.FinalState.Cell}`)");
        sb.AppendLine();

        if (r.CompileErrors.Count > 0)
        {
            sb.AppendLine("### Compile errors");
            foreach (var e in r.CompileErrors.Take(20))
                sb.AppendLine($"- `{e}`");
            sb.AppendLine();
        }
        if (!string.IsNullOrEmpty(r.ExceptionText))
        {
            sb.AppendLine("### Script exception");
            sb.AppendLine("```text");
            sb.AppendLine(r.ExceptionText);
            sb.AppendLine("```");
            sb.AppendLine();
        }
        if (r.ScriptLogs.Count > 0)
        {
            sb.AppendLine("### Script log (last 30 lines)");
            sb.AppendLine("```text");
            foreach (var log in r.ScriptLogs.TakeLast(30))
                sb.AppendLine($"[{log.Clock}] {log.Text}");
            sb.AppendLine("```");
            sb.AppendLine();
        }
        if (r.Warnings.Count > 0)
        {
            sb.AppendLine("### Simulator warnings (last 15)");
            foreach (var w in r.Warnings.TakeLast(15))
                sb.AppendLine($"- `[{w.Clock}]` {w.Text}");
            sb.AppendLine();
        }
        if (r.ServerMessages.Count > 0)
        {
            sb.AppendLine("### Server messages");
            foreach (var (text, count) in r.ServerMessages.OrderByDescending(kv => kv.Value).Take(15))
                sb.AppendLine($"- `{text}`: {count:N0}");
            sb.AppendLine();
        }
    }

    private static void AppendDataGaps(StringBuilder sb, SimulationReport r)
    {
        sb.AppendLine("## How much to trust this reproduction");
        if (r.SynthesizedMaps.Count == 0 && r.SynthesizedData.Count == 0 && r.UnimplementedCalls.Count == 0 && r.MissingUnlockItems.Count == 0)
        {
            sb.AppendLine("- No invented data and no unimplemented API members: the run used collected data and the diagnostic only.");
            sb.AppendLine();
            return;
        }
        if (r.SynthesizedMaps.Count > 0)
            sb.AppendLine($"- **Maps never collected** (monsters and cells invented; run the Collector there): {string.Join(", ", r.SynthesizedMaps.Select(m => $"`{m}`"))}");
        // An uncollected shop is as decisive as an uncollected map: what it sells (merges, quest items) is unknown.
        var shops = r.SynthesizedData.Where(s => s.Key.StartsWith("shop:", StringComparison.Ordinal)).ToList();
        if (shops.Count > 0)
            sb.AppendLine($"- **Shops never collected** (what they sell is unknown, so purchases and merges from them cannot happen as in game; " +
                          $"open them in game with the Collector running): {string.Join(", ", shops.Select(s => $"`{s.Key["shop:".Length..]}`"))}");
        if (r.SynthesizedData.Count > 0)
        {
            sb.AppendLine($"- **Invented data** ({r.SynthesizedData.Count} record(s)); results that depend on it may differ from the real game:");
            foreach (var s in r.SynthesizedData.OrderByDescending(s => s.Count).Take(10))
                sb.AppendLine($"  - `[{s.Key}]` x{s.Count}: {s.Description}");
            if (r.SynthesizedData.Count > 10)
                sb.AppendLine($"  - … and {r.SynthesizedData.Count - 10} more (see the full report).");
        }
        if (r.UnimplementedCalls.Count > 0)
            sb.AppendLine($"- **Unimplemented API members** (returned defaults): {string.Join(", ", r.UnimplementedCalls.OrderByDescending(kv => kv.Value).Take(10).Select(kv => $"`{kv.Key}` x{kv.Value:N0}"))}");
        if (r.MissingUnlockItems.Count > 0)
            sb.AppendLine($"- **Items the script checked but the character does not own:** {string.Join(", ", r.MissingUnlockItems.Take(10).Select(m => $"`{m.Name}`"))}");
        sb.AppendLine();
    }

    private static void AppendRegressionTest(StringBuilder sb, Scenario d, SimulationReport r, string? diagnosticPath)
    {
        sb.AppendLine("## Regression test (after the fix)");
        sb.AppendLine("Copy the diagnostic into `scenarios\\`, pin it to a data snapshot (`\"dataSnapshot\"`), replace the placeholders below with " +
                      "what the fixed script must achieve, add them as `\"asserts\"`, and run `skuasim test`. Until the fix, the asserts should fail on this run.");
        sb.AppendLine();
        sb.AppendLine("```jsonc");
        sb.AppendLine("\"asserts\": [");
        sb.AppendLine("  { \"check\": \"outcome\", \"is\": [\"Completed\"] },");
        if (string.IsNullOrWhiteSpace(d.Script))
            sb.AppendLine($"  // also set \"script\": \"{r.ScriptPath.Replace("\\", "\\\\")}\" in the scenario");
        sb.AppendLine("  { \"check\": \"synthesizedMaps\" },  // no invented maps (collect them first)");
        sb.AppendLine("  { \"check\": \"item\", \"name\": \"<item the script must get>\", \"min\": 1 },");
        sb.AppendLine("  { \"check\": \"questCompleted\", \"quest\": 0 }  // <quest the script must finish>");
        sb.AppendLine("]");
        sb.AppendLine("```");
        if (r.Assertions.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine($"The diagnostic already has {r.Assertions.Count} assert(s): {r.Assertions.Count - r.AssertionsFailed} passed, {r.AssertionsFailed} failed.");
            foreach (var a in r.Assertions.Where(a => !a.Passed))
                sb.AppendLine($"- **FAIL** {a.Description}: expected {a.Expected}, got {a.Actual}");
        }
        sb.AppendLine();
    }

    private static string Cell(string text) => text.Replace("|", "\\|").Replace('\n', ' ');

    private static string FormatVirtual(TimeSpan t) =>
        $"{(int)t.TotalHours:00}:{t.Minutes:00}:{t.Seconds:00}";
}
